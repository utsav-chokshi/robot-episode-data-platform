"""Resolve and hash CPU Linux/amd64 Python 3.12 dashboard wheels."""
import hashlib,subprocess,tempfile
from pathlib import Path
from packaging.utils import parse_wheel_filename
root=Path('/workspace')
with tempfile.TemporaryDirectory() as temporary:
    subprocess.run(['python','-m','pip','download','--only-binary=:all:','--dest',temporary,'-r',str(root/'requirements-dashboard.in')],check=True)
    lines=['# Linux/amd64 CPython 3.12 wheel lock; generated by scripts/lock-dashboard.py.']
    for path in sorted(Path(temporary).glob('*.whl')):
        name,version,_,_=parse_wheel_filename(path.name)
        with path.open('rb') as source:
            checksum=hashlib.file_digest(source,'sha256').hexdigest()
        lines.append(f'{name}=={version} --hash=sha256:{checksum}')
    (root/'requirements-dashboard.lock').write_text('\n'.join(lines)+'\n')
