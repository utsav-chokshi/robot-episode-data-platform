"""Generate a hashed Linux/amd64 CPython 3.12 wheel lock from exact pins.

Run in a Python container with packaging installed. Downloads wheels only,
not every architecture's Torch build; pip check validates the installed closure.
"""
import hashlib
import subprocess
import tempfile
from pathlib import Path
from packaging.utils import parse_wheel_filename

root = Path('/workspace')
with tempfile.TemporaryDirectory() as temporary:
    subprocess.run(['python','-m','pip','download','--only-binary=:all:','--no-deps','--dest',temporary,'--extra-index-url','https://download.pytorch.org/whl/cpu','-r',str(root/'requirements-vlm.in')],check=True)
    lines = ['# Linux/amd64 CPython 3.12 CPU wheels; generated by scripts/lock-vlm.py.',
             '--extra-index-url https://download.pytorch.org/whl/cpu','']
    for path in sorted(Path(temporary).glob('*.whl')):
        name,version,_,_ = parse_wheel_filename(path.name)
        checksum = hashlib.file_digest(path.open('rb'),'sha256').hexdigest()
        lines.append(f'{name}=={version} --hash=sha256:{checksum}')
    (root/'requirements-vlm.lock').write_text('\n'.join(lines)+'\n')
